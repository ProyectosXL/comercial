-- Script para crear la tabla de rotaciones de imágenes
-- Ejecutar en la base de datos central

IF NOT EXISTS (SELECT * FROM sysobjects WHERE name='RO_T_ROTACION_IMAGENES_SUP' AND xtype='U')
BEGIN
    CREATE TABLE RO_T_ROTACION_IMAGENES_SUP (
        ID INT IDENTITY(1,1) PRIMARY KEY,
        NOMBRE_IMAGEN VARCHAR(500) NOT NULL UNIQUE,
        ROTACION INT NOT NULL DEFAULT 0,
        ID_CONC INT NULL,
        SEMANA INT NULL,
        ANIO INT NULL,
        SUPERVISORA VARCHAR(200) NULL,
        TIPO VARCHAR(50) NULL, -- 'tarjeta' o 'efectivo'
        FECHA_CREACION DATETIME NOT NULL DEFAULT GETDATE(),
        FECHA_MODIFICACION DATETIME NULL
    )
    
    CREATE INDEX IX_ROTACION_IMAGENES_NOMBRE ON RO_T_ROTACION_IMAGENES_SUP(NOMBRE_IMAGEN)
    
    PRINT 'Tabla RO_T_ROTACION_IMAGENES_SUP creada exitosamente'
END
ELSE
BEGIN
    PRINT 'La tabla RO_T_ROTACION_IMAGENES_SUP ya existe'
END
GO
