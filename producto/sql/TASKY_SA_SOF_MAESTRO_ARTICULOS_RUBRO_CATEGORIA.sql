-- Uruguay toma las correcciones de categoría de Argentina.
-- La vista de TASKY_SA pasa a leer LAKER_SA.dbo.SOF_T_MAESTRO_ARTICULOS_RUBRO_CATEGORIA_AUX (la misma que
-- carga Gestión de Categorías > Reasignar Categorías), así una corrección aplica a los dos países.
-- Solo se toma CATEGORIA: el RUBRO de la AUX sigue las reglas de Argentina (ej. TOALLAS -> HOME) y
-- esta vista no tiene CATEGORIA_PADRE.
-- Ejecutar en XL-TANGO / TASKY_SA.

USE TASKY_SA;
GO

-- 0) ANTES DE APLICAR: artículos de Uruguay cuya categoría va a cambiar por correcciones que ya existen en la AUX
SELECT A.COD_ARTICU, B.DESC_CATEGORIA AS CATEGORIA_ACTUAL_UY, X.CATEGORIA AS CATEGORIA_AUX
FROM (
    SELECT COD_ARTICU, SUBSTRING(COD_ARTICU, 9, 1) SIGLA_RUBRO, SUBSTRING(COD_ARTICU, 10, 2) SIGLA_CAT
    FROM STA11 WITH (NOLOCK)
    WHERE FECHA_ALTA >= '2019-01-01' AND COD_ARTICU NOT LIKE '%[-]%' AND USA_ESC = 'S'
) A
LEFT JOIN SJ_CATEGORIAS B ON A.SIGLA_RUBRO = B.RUBRO AND A.SIGLA_CAT = B.CATEGORIA
INNER JOIN LAKER_SA.DBO.SOF_T_MAESTRO_ARTICULOS_RUBRO_CATEGORIA_AUX X ON A.COD_ARTICU = X.COD_ARTICU COLLATE Latin1_General_BIN
WHERE ISNULL(B.DESC_CATEGORIA, '') <> ISNULL(X.CATEGORIA, '') COLLATE DATABASE_DEFAULT
ORDER BY A.COD_ARTICU;
GO

-- 1) Vista con la AUX de Argentina (cambios respecto de la original marcados con "AUX")
ALTER VIEW SOF_MAESTRO_ARTICULOS_RUBRO_CATEGORIA AS

--CATEGORIAS NUEVA CODIFICACION--

SELECT A.COD_ARTICU, A.MODELO, A.DESCRIPCION, C.DESC_VALOR COLOR, A.RUBRO,
A.CATEGORIA,
CASE WHEN B.DESTINO IS NULL THEN 'SIN' ELSE B.DESTINO END DESTINO,
CASE WHEN B.TEMPORADA IS NULL THEN 'SIN' ELSE TEMPORADA END TEMPORADA,
ISNULL(ISNULL(D.NOM_PROVEE, E.PROVEEDOR),
(CASE WHEN A.COD_ARTICU LIKE 'XC%' THEN 'CUERO BA SRL' ELSE NULL END)) PROVEEDOR

--CASE WHEN D.NOM_PROVEE IS NULL THEN E.PROVEEDOR WHEN E.PROVEEDOR IS NULL THEN D.NOM_PROVEE ELSE 'SIN ASIGNAR' END PROVEEDOR
FROM
(
SELECT A.COD_ARTICU, LEFT(A.COD_ARTICU,13) MODELO, A.DESCRIPCIO DESCRIPCION, A.ESCALA_1, A.VALOR1, C.RUBRO,
-- AUX: primero la corrección manual de LAKER_SA, si no hay se calcula desde SJ_CATEGORIAS
COALESCE(X.CATEGORIA COLLATE DATABASE_DEFAULT, B.DESC_CATEGORIA) CATEGORIA
FROM
(
SELECT COD_ARTICU, DESCRIPCIO, ESCALA_1, VALOR1, SUBSTRING(COD_ARTICU, 9, 1) SIGLA_RUBRO , SUBSTRING(COD_ARTICU, 10, 2) SIGLA_CAT FROM STA11  WITH (NOLOCK)
WHERE FECHA_ALTA >= '2019-01-01' AND COD_ARTICU NOT LIKE '%[-]%' AND USA_ESC = 'S'
) A
LEFT JOIN SJ_CATEGORIAS B ON A.SIGLA_RUBRO = B.RUBRO AND A.SIGLA_CAT = B.CATEGORIA
LEFT JOIN LAKER_SA.DBO.SOF_RUBROS_TANGO C ON A.COD_ARTICU = C.COD_ARTICU
-- AUX: solo las columnas necesarias, para no chocar con las de STA11 (la AUX también tiene DESCRIPCIO)
LEFT JOIN (SELECT COD_ARTICU, CATEGORIA FROM LAKER_SA.DBO.SOF_T_MAESTRO_ARTICULOS_RUBRO_CATEGORIA_AUX) X
    ON A.COD_ARTICU = X.COD_ARTICU COLLATE Latin1_General_BIN
) A

LEFT JOIN MAESTRO_DESTINOS B ON A.COD_ARTICU = B.COD_ARTICU COLLATE Latin1_General_BIN
LEFT JOIN (SELECT COD_ESCALA, COD_VALOR, DESC_VALOR FROM STA33 WHERE COD_ESCALA = '**' OR COD_ESCALA = 'ZZ' ) C ON A.ESCALA_1 = C.COD_ESCALA AND A.VALOR1 = C.COD_VALOR
--LEFT JOIN (SELECT COD_ARTICU, NOM_PROVEE PROVEDOR FROM CPA15 A INNER JOIN CPA01 B ON A.COD_CPA01_PROVEEDOR = B.COD_CPA01) D ON A.COD_ARTICU = D.COD_ARTICU
LEFT JOIN SJ_PROVEEDORES D ON A.COD_ARTICU = D.COD_ARTICU
LEFT JOIN (SELECT COD_ARTICU, MAX(NOM_PROVEE) PROVEEDOR FROM CPA15 A WITH (NOLOCK) INNER JOIN CPA01 B ON A.COD_CPA01_PROVEEDOR = B.COD_CPA01 GROUP BY COD_ARTICU) E ON A.COD_ARTICU = E.COD_ARTICU
GO

